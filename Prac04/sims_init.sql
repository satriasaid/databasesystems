SHOW DATABASES;

USE dswork;

SHOW TABLES;

CREATE TABLE Student(studentNo CHAR(8) NOT NULL PRIMARY KEY, name VARCHAR(25) NOT NULL, phone VARCHAR(25));

CREATE TABLE Unit(unitNo VARCHAR(8) NOT NULL PRIMARY KEY, title VARCHAR(40) NOT NULL, crePts INT(3) NOT NULL);

CREATE TABLE Building(bNo VARCHAR(3) NOT NULL PRIMARY KEY, bName VARCHAR(40) NOT NULL);

CREATE TABLE Room(roomNo VARCHAR(3) NOT NULL PRIMARY KEY, bNo VARCHAR(3), capacity INT(3) NOT NULL, type VARCHAR(40) NOT NULL, CONSTRAINT fk_bNo FOREIGN KEY (bNo) REFERENCES Building(bNo));
